#celsius to fahrenheit
celsius = 25
fahrenheit = (celsius * 9/5) + 32
print(f"{celsius} degrees Celsius is equal to {fahrenheit} degrees Fahrenheit.")

#farenheit to celsius
farenheit = 77
celsius = (fahrenheit - 32) * 5/9
print(f"{farenheit} degrees Fahrenheit is equal to {celsius} degrees Celsius.")

#minutes to seconds
minutes = 20
seconds = minutes * 60
print(f"{minutes} minutes is equal to {seconds} seconds.")

#hours to minutes
hours = 2
minutes = hours * 60
print(f"{hours} hours is equal to {minutes} minutes.")

#kilograms to grams
kilograms = 65
grams = kilograms * 1000
print(f"{kilograms} kilograms is equal to {grams} grams.")
